#!/usr/bin/env node
// Creates apps/web/.env.local with fresh app secrets and the Supabase public settings.
// Secrets are generated locally and written straight to the file (mode 600) — never printed.
//
//   node scripts/setup-env.mjs --url https://<ref>.supabase.co --anon <anon-or-publishable-key>
//
// Afterwards paste SUPABASE_SERVICE_ROLE_KEY into the file yourself (Supabase → Project Settings →
// API keys). To deploy, import the same file into Vercel (Settings → Environment Variables → Import .env).
import { existsSync, writeFileSync } from "node:fs";
import { randomBytes, generateKeyPairSync } from "node:crypto";
import { join } from "node:path";
import { fileURLToPath } from "node:url";

const args = Object.fromEntries(process.argv.slice(2).reduce((acc, a, i, all) => (a.startsWith("--") ? [...acc, [a.slice(2), all[i + 1]]] : acc), []));
const target = join(fileURLToPath(import.meta.url), "..", "..", "apps", "web", ".env.local");

if (!args.url || !/^https:\/\/[a-z0-9]+\.supabase\.co$/.test(args.url)) throw new Error("--url must look like https://<ref>.supabase.co");
if (!args.anon || args.anon.length < 20) throw new Error("--anon is required");
if (/service|secret/i.test(args.anon) || args.anon.startsWith("sb_secret_")) throw new Error("--anon must be the public anon/publishable key, not a secret key");
if (existsSync(target) && !("force" in args)) throw new Error(`${target} already exists — pass --force to replace it`);

const b64 = (b) => Buffer.from(b).toString("base64");
const der = generateKeyPairSync("ed25519").privateKey.export({ format: "der", type: "pkcs8" });

const lines = [
  "# Generated by scripts/setup-env.mjs — never commit this file.",
  `NEXT_PUBLIC_SUPABASE_URL=${args.url}`,
  `NEXT_PUBLIC_SUPABASE_ANON_KEY=${args.anon}`,
  "# Paste the service_role / secret key here (Supabase → Project Settings → API keys). SERVER ONLY.",
  "SUPABASE_SERVICE_ROLE_KEY=",
  `HM_MASTER_KEY=${b64(randomBytes(32))}`,
  `HM_SIGNING_KEY=${b64(der.subarray(der.length - 32))}`,
  `HM_MEDIA_HMAC_KEY=${b64(randomBytes(32))}`,
  `HM_EXT_TOKEN_PEPPER=${b64(randomBytes(32))}`,
  `HM_WATERMARK_KEY=${b64(randomBytes(32))}`,
  "CODE_RUNNER=piston",
  "PISTON_URL=http://127.0.0.1:2000",
  "",
];
writeFileSync(target, lines.join("\n"), { mode: 0o600 });
console.log(`wrote ${target} (secrets generated, not shown). Next: paste SUPABASE_SERVICE_ROLE_KEY into it.`);
